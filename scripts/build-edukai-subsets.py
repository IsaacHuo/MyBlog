#!/usr/bin/env python3
"""Build WOFF2 subsets of the edukai (教育部標準楷書) font for the blog.

Outputs public/fonts/edukai/*.woff2 and .vitepress/theme/edukai-fonts.css:
  * BlogEdukaiSite    - every character the Chinese site renders (after the
                        Traditional conversion), font-display: block.
  * BlogEdukai        - unicode-range chunks as an on-demand fallback for
                        characters added later or rendered at runtime.
Re-run after adding Chinese text:  npm run fonts:edukai
"""
from __future__ import annotations
import sys
sys.stdout.reconfigure(encoding="utf-8")

import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEPS = ROOT / ".fontdeps"
CACHED_TTF = DEPS / "edukai.ttf"
ZIP_SOURCE = Path.home() / "Downloads" / "17694979891080.zip"
OUTPUT_DIR = ROOT / "public" / "fonts" / "edukai"
CSS_FILE = ROOT / ".vitepress" / "theme" / "edukai-fonts.css"
PINNED = ["fonttools==4.68.0", "brotli==1.1.0"]


def ensure_deps() -> dict[str, str]:
    env = {**os.environ, "PYTHONPATH": str(DEPS)}
    probe = subprocess.run([sys.executable, "-c", "import fontTools, brotli"], env=env)
    if probe.returncode != 0:
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "--quiet", "--target", str(DEPS), *PINNED],
            check=True,
        )
    return env


def source_font() -> Path:
    explicit = os.environ.get("EDUKAI_SOURCE_TTF")
    if explicit and Path(explicit).is_file():
        return Path(explicit)
    if CACHED_TTF.is_file():
        return CACHED_TTF
    if ZIP_SOURCE.is_file():
        with zipfile.ZipFile(ZIP_SOURCE) as archive:
            name = next((n for n in archive.namelist() if n.lower().endswith(".ttf")), None)
            if name:
                DEPS.mkdir(exist_ok=True)
                CACHED_TTF.write_bytes(archive.read(name))
                return CACHED_TTF
    raise SystemExit("edukai TTF not found. Set EDUKAI_SOURCE_TTF=/path/edukai-5.1.ttf")


def unicode_range(codepoints: list[int]) -> str:
    ranges: list[tuple[int, int]] = []
    start = prev = codepoints[0]
    for cp in codepoints[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        ranges.append((start, prev))
        start = prev = cp
    ranges.append((start, prev))
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in ranges)


def subset(env: dict[str, str], source: Path, output: Path, *, text_file: Path | None = None, unicodes: str | None = None) -> None:
    cmd = [
        sys.executable, "-m", "fontTools.subset", str(source),
        f"--output-file={output}", "--flavor=woff2",
        "--layout-features=*", "--no-hinting", "--desubroutinize",
        "--name-IDs=*", "--notdef-outline",
    ]
    cmd.append(f"--text-file={text_file}" if text_file else f"--unicodes={unicodes}")
    subprocess.run(cmd, check=True, env=env)


def font_face(family: str, file_name: str, range_value: str, display: str) -> str:
    return (
        "@font-face {\n"
        f'  font-family: "{family}";\n'
        f'  src: url("/fonts/edukai/{file_name}") format("woff2");\n'
        "  font-style: normal;\n"
        "  font-weight: 400;\n"
        f"  font-display: {display};\n"
        f"  unicode-range: {range_value};\n"
        "}"
    )


def chunk_ranges(cmap: set[int]) -> list[tuple[str, int, int]]:
    spans = [("symbols", 0x3000, 0x303F), ("fullwidth", 0xFF00, 0xFFEF)]
    for start in range(0x3400, 0x4DC0, 0x800):
        spans.append((f"ext-a-{start:04x}", start, min(start + 0x7FF, 0x4DBF)))
    for start in range(0x4E00, 0xA000, 0x800):
        spans.append((f"cjk-{start:04x}", start, min(start + 0x7FF, 0x9FFF)))
    spans.append(("compat", 0xF900, 0xFAFF))
    return [s for s in spans if any(s[1] <= cp <= s[2] for cp in cmap)]


def main() -> None:
    env = ensure_deps()
    sys.path.insert(0, str(DEPS))
    from fontTools.ttLib import TTFont  # noqa: E402

    source = source_font()
    cmap = set(TTFont(source).getBestCmap())

    if OUTPUT_DIR.exists():
        shutil.rmtree(OUTPUT_DIR)
    OUTPUT_DIR.mkdir(parents=True)

    site_text = OUTPUT_DIR / "site-chars.txt"
    node = shutil.which("node") or "node"
    subprocess.run([node, str(ROOT / "scripts" / "collect-zh-text.mjs"), str(site_text)], check=True)
    chars = site_text.read_text("utf-8")
    covered = sorted({ord(c) for c in chars} & cmap)
    missing = sorted({c for c in chars if ord(c) not in cmap})

    css = ["/* Generated by scripts/build-edukai-subsets.py. Do not edit. */"]
    subset(env, source, OUTPUT_DIR / "edukai-site.woff2", text_file=site_text)
    css.append(font_face("BlogEdukaiSite", "edukai-site.woff2", unicode_range(covered), "block"))

    for name, start, end in chunk_ranges(cmap):
        file_name = f"edukai-{name}.woff2"
        subset(env, source, OUTPUT_DIR / file_name, unicodes=f"U+{start:04X}-{end:04X}")
        css.append(font_face("BlogEdukai", file_name, f"U+{start:04X}-{end:04X}", "swap"))

    CSS_FILE.write_text("\n\n".join(css) + "\n", "utf-8")
    site_text.unlink()

    site_size = (OUTPUT_DIR / "edukai-site.woff2").stat().st_size
    total = sum(p.stat().st_size for p in OUTPUT_DIR.glob("*.woff2"))
    print(f"Site subset: {len(covered)} chars, {site_size / 1024:.0f} KB")
    print(f"All subsets: {len(list(OUTPUT_DIR.glob('*.woff2')))} files, {total / 1024 / 1024:.2f} MB")
    if missing:
        print(f"Not in edukai ({len(missing)}), falls back to system Kai: {''.join(missing)}")


if __name__ == "__main__":
    main()
